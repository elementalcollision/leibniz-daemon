"""Amplify arXiv 2607.19029 §7 — the distinct covering system with minimum modulus 7 and least
common multiple 10080 — into a promulgated LAW, labelled ``amplified`` + ``kernel-decided``.

This is the target ADR 0088 widened the mixed-modulus fragment for and ADR 0090 unblocked at the
parse boundary. Unlike the earlier amplifications, the theorem and its proof are **generated by
the daemon's own decision procedure**, not hand-written: ``mixed_modulus_prover.mixed_law`` renders
the canonical ℤ-box statement and the ADR 0060 LCM/castHom proof (one ``decide`` over
``ZMod 10080``, one ``intCast`` bridge per atom). The script asserts they came out of the
generator, so a hand-edited law cannot be published through this path.

WHAT IS AMPLIFIED, precisely: the CONSTRUCTION half of the paper's Theorem 1 — that these 66
congruence classes cover the integers, with distinct moduli, least modulus 7, lcm exactly 10080.

WHAT IS NOT: that 10080 is MINIMAL. That is the paper's actual theorem (L_min(7) = 10080), it
rules out every smaller lcm, and it rests on complete Gurobi computations — a commercial ILP
solver standing where a mechanical checker should. Nothing here speaks to it, and re-deciding it
is out of reach. The law's statement says so rather than implying the whole theorem was amplified.

Trust boundary UNTOUCHED: ``kernel_verified`` is written only by ``LeanVerifier.discharge``;
``axiom_closure`` re-checks the whole assembled source; plain ``decide``, no ``native_decide``, no
``sorryAx``. ``tier``/``origination``/``references`` are report-only (ADR 0050).

Usage:  PYTHONPATH=. python scripts/export_covering10080_law.py [--write]
"""
