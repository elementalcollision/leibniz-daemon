_REFERENCES = [
    {"citation": ("Zhang, S. & Zhang, J. (2026). A Distinct Covering System with Minimum Modulus 7 "
                  "and Minimal Least Common Multiple 10080. arXiv:2607.19029."),
     "url": "https://arxiv.org/abs/2607.19029"},
]


def verify_transcription() -> dict:
    """Re-derive every property the law names, from the list itself. A mistranscribed residue would
    otherwise make the kernel certify a DIFFERENT object than the one cited."""
    M = 10080
    mods = [m for m, _ in SYSTEM]
    lcm = 1
    for m in mods:
        lcm = lcm * m // math.gcd(lcm, m)
    hit = [False] * M
    for m, c in SYSTEM:
        for x in range(c % m, M, m):
            hit[x] = True
    facts = {
        "n_congruences": len(SYSTEM),
        "moduli_distinct": len(set(mods)) == len(mods),
        "min_modulus": min(mods),
        "lcm": lcm,
        "all_moduli_divide_lcm": all(lcm % m == 0 for m in mods),
        "residues_in_range": all(0 <= c < m for m, c in SYSTEM),
        "uncovered_residues": sum(1 for h in hit if not h),
    }
    facts["ok"] = (facts["moduli_distinct"] and facts["min_modulus"] == 7 and facts["lcm"] == M
                   and facts["all_moduli_divide_lcm"] and facts["residues_in_range"]
                   and facts["uncovered_residues"] == 0)
    return facts


def claim_property() -> str:
    return " or ".join(f"(n % {m} == {c})" for m, c in SYSTEM)


def build_propositio() -> Propositio:
    got = mixed_law(_NAME, "n >= 0", claim_property())
    if got is None:
        raise SystemExit("mixed_law abstained — the claim is outside the mixed-modulus fragment")
    theorem_src, proof_src = got
    en = Enuntiatio(
        statement=("A distinct covering system with minimum modulus 7 and least common multiple "
                   "10080 exists (Zhang & Zhang 2026, §7) — kernel-decided construction half: the "
                   "66 exhibited congruence classes cover every n ≥ 0, their moduli are distinct, "
                   "the least is 7 and their lcm is exactly 10080. The paper's MINIMALITY claim "
                   "(L_min(7) = 10080), which rests on complete Gurobi computations, is NOT "
                   "amplified here and is not implied by this law."),
        claim_type=ClaimType.CORRECTNESS_OVER_DOMAIN,
        falsifiable_claim=("an integer n ≥ 0 lying in none of the 66 classes — equivalently a "
                           "residue mod 10080 left uncovered"),
        claim_domain="n >= 0",
        claim_property=claim_property(),
        domain="number_theory",
    )
    ex = Expressio(theorem_src=theorem_src, imports=("Mathlib",))
    de = Demonstratio(proof_obligation=_NAME, proof_src=proof_src)
    return Propositio(enuntiatio=en, expressio=ex, demonstratio=de)


def main() -> int:
    write = "--write" in sys.argv
    facts = verify_transcription()
    print("=== amplification: arXiv 2607.19029 §7 → covering system law ===")
    print(f"  transcription   : {facts}")
    if not facts["ok"]:
        print("!! the congruence list does not have the cited properties — refusing to proceed.")
        return 1
    if not available():
        print("Lean kernel unavailable (docker/image) — cannot discharge. Aborting.")
        return 2

    prop = build_propositio()
    ex, de = prop.expressio, prop.demonstratio
    # the law must come from the GENERATOR, not from an edit of this file
    regen = mixed_law(_NAME, "n >= 0", claim_property())
    if regen != (ex.theorem_src, de.proof_src):
        print("!! theorem/proof are not what the generator emits — refusing to proceed.")
        return 1

    from leibniz.verifiers import LeanVerifier
    be = LeanReplBackend(timeout_s=900)
    try:
        edge = LeanVerifier(be).discharge(ex, de)          # THE ONLY kernel_verified writer
        ax = axiom_closure(be, ex.theorem_src, de.proof_src, ex.imports, preamble=ex.preamble)
    finally:
        be.close()

    print("  generator       : mixed_modulus_prover.mixed_law (ADR 0060 LCM/castHom)")
    print(f"  kernel_verified : {de.kernel_verified}")
    print(f"  qed             : {de.qed}")
    print(f"  proof edge      : {edge.verdict.value} (producer {edge.producer}, tier {edge.tier.name})")
    print(f"  axiom_closure   : ok={ax['ok']} axioms={ax.get('axioms')} saw_report={ax.get('saw_axiom_report')}")
    if not (de.kernel_verified and de.qed == "Q.E.D." and ax["ok"]):
        print("!! discharge or axiom check failed — NOT emitting a law.")
        return 1

    prop.promulgated = True
    payload = law_payload(prop, published_at="", specimen=False,
                          tier="kernel-decided", origination="amplified", references=_REFERENCES)
    payload["$schema"] = "../../../.astro/collections/laws.schema.json"
    print(f"\n  law id          : {payload['id']}")
    print(f"  tier/origination: {payload['tier']} / {payload['origination']}")
    print(f"  artifact        : {_ARTIFACT.relative_to(_ROOT)}")
    print(f"  theorem_src     : {len(payload['theorem_src'])} chars")
    if write:
        _OUT.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
        print(f"\n  WROTE {_OUT.relative_to(_ROOT)}")
    else:
        print("\n  (dry run — pass --write to emit the law JSON; publication is the operator's "
              "ADR 0033 act)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
